    sb.AppendLine($"    public const string {MethodIdent(m.Name)} = \"{m.Name}\";");
sb.AppendLine("    public static readonly IReadOnlyList<PaguroMethodInfo> All = new PaguroMethodInfo[]");
sb.AppendLine("    {");
foreach (var m in methods.EnumerateObject())
{
    var v = m.Value;
    string Strs(string prop) => v.TryGetProperty(prop, out var a)
        ? "new[] { " + string.Join(", ", a.EnumerateArray().Select(x => Lit(x.GetString()!))) + " }"
        : "System.Array.Empty<string>()";
    var stub = v.TryGetProperty("stub", out var s) ? Lit(s.GetString()!) : "null";
    var progress = v.TryGetProperty("progress", out var pr) && pr.GetBoolean() ? "true" : "false";
    var dry = v.TryGetProperty("dry_run_read", out var dr) && dr.GetBoolean() ? "true" : "false";
    var pName = ClassOf(RefName(v.GetProperty("params")));
    var rName = ClassOf(RefName(v.GetProperty("result")));
    sb.AppendLine($"        new PaguroMethodInfo({Lit(m.Name)}, {Lit(v.GetProperty("access").GetString()!)}, {Lit(v.GetProperty("cli").GetString()!)}, {Strs("cli_example")}, {Strs("cmdlets")}, typeof({pName}), typeof({rName}), {progress}, {stub}, {Strs("gated")}, {dry}),");
