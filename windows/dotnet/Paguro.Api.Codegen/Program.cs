static string RefName(JsonElement e) => e.GetProperty("$ref").GetString()!.Replace("#/$defs/", "");
static string ClassOf(string def) => def == "CommonParams" ? "ParamsBase" : def;
static bool IsClass(string t) => !(t is "string" or "bool" or "long" or "ulong" or "double" or "JsonNode");

static (string Type, bool Nullable) TypeOf(JsonElement s)
{
    if (s.TryGetProperty("$ref", out _)) return (ClassOf(RefName(s)), false);
    if (s.TryGetProperty("anyOf", out var any))
    {
        var branches = any.EnumerateArray().ToList();
        var nonNull = branches.Where(b => !(b.TryGetProperty("type", out var t) && t.ValueKind == JsonValueKind.String && t.GetString() == "null")).ToList();
        if (nonNull.Count == 1) return (TypeOf(nonNull[0]).Type, branches.Count > 1);
        return ("JsonNode", true);
    }
    if (!s.TryGetProperty("type", out var type)) return ("JsonNode", true);
    var nullable = false;
    string? t0;
    if (type.ValueKind == JsonValueKind.Array)
    {
        var ts = type.EnumerateArray().Select(x => x.GetString()!).ToList();
        nullable = ts.Contains("null");
        t0 = ts.FirstOrDefault(x => x != "null");
    }
    else t0 = type.GetString();
    var format = s.TryGetProperty("format", out var f) ? f.GetString() : null;
    var cs = t0 switch
    {
        "string" => "string",
        "boolean" => "bool",
        "integer" => format == "uint64" ? "ulong" : "long",
        "number" => "double",
        "array" => $"List<{Elem(s)}>",
        "object" => "JsonNode",
        _ => "JsonNode",
    };
    return (cs, nullable);
}

static string Elem(JsonElement s)
{
    if (!s.TryGetProperty("items", out var it)) return "JsonNode";
    var (t, n) = TypeOf(it);
    return n && !t.EndsWith("?") ? t + "?" : t;
}

static string Pascal(string snake)
{
    var parts = snake.Split('_', '-', '.');
    var s = string.Concat(parts.Where(p => p.Length > 0).Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
    return s == "Extra" ? "ExtraField" : s;
}

static string MethodIdent(string m) => Pascal(m.Replace('.', '_').Replace('-', '_'));

static string Lit(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

static void Doc(StringBuilder sb, JsonElement s, string indent)
{
    if (s.TryGetProperty("description", out var d) && d.GetString() is { Length: > 0 } text)
        sb.AppendLine($"{indent}/// <summary>{Xml(text)}</summary>");
}
