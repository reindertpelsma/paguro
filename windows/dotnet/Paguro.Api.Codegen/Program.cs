    var v = m.Value;
    var pName = ClassOf(RefName(v.GetProperty("params")));
    var rName = ClassOf(RefName(v.GetProperty("result")));
    sb.AppendLine($"    /// <summary>{Xml(v.GetProperty("summary").GetString()!)} (<c>{m.Name}</c>, {v.GetProperty("access").GetString()})</summary>");
    sb.AppendLine($"    public static Task<PaguroResult<{rName}>> {MethodIdent(m.Name)}Async(this IPaguroClient client, {pName}? parameters = null, System.IProgress<Progress>? progress = null, CancellationToken cancel = default)");
