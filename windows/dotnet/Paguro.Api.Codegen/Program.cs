// paguro-api.json -> C# (INTERFACES.md §11.7: "Rust types and C# types both
// generated from it"). Usage: Paguro.Api.Codegen <schema.json> <out.cs>
//
// - every $defs entry becomes a class; `CommonParams` becomes the abstract
//   `ParamsBase` every *Params class derives from;
// - JSON names stay snake_case on the wire ([JsonPropertyName]), properties
//   are PascalCase; optional or null-able fields are nullable;
// - data classes keep unknown fields ([JsonExtensionData]): the API adds
//   fields without a version bump;
// - `PaguroMethods` has one constant per method and the method table;
//   `PaguroCalls` one typed extension method per method on IPaguroClient.
using System.Text;
using System.Text.Json;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: Paguro.Api.Codegen <paguro-api.json> <out.cs>");
    return 2;
}
using var doc = JsonDocument.Parse(File.ReadAllText(args[0]));
var root = doc.RootElement;
var defs = root.GetProperty("$defs");
var methods = root.GetProperty("methods");
var paramDefs = new HashSet<string>();
foreach (var m in methods.EnumerateObject())
    paramDefs.Add(RefName(m.Value.GetProperty("params")));

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated> from windows/api/paguro-api.json by Paguro.Api.Codegen. Do not edit. </auto-generated>");
sb.AppendLine("#nullable enable");
sb.AppendLine("using System.Collections.Generic;");
sb.AppendLine("using System.Text.Json;");
sb.AppendLine("using System.Text.Json.Nodes;");
sb.AppendLine("using System.Text.Json.Serialization;");
sb.AppendLine("using System.Threading;");
sb.AppendLine("using System.Threading.Tasks;");
sb.AppendLine();
sb.AppendLine("namespace Paguro.Api;");
sb.AppendLine();

foreach (var d in defs.EnumerateObject())
{
    var name = d.Name == "CommonParams" ? "ParamsBase" : d.Name;
    var isParams = paramDefs.Contains(d.Name);
    var isBase = d.Name == "CommonParams";
    Doc(sb, d.Value, "");
    var kw = isBase ? "public abstract partial class" : "public sealed partial class";
    var inherit = isParams ? " : ParamsBase" : "";
    sb.AppendLine($"{kw} {name}{inherit}");
    sb.AppendLine("{");
    var required = new HashSet<string>();
    if (d.Value.TryGetProperty("required", out var req))
        foreach (var r in req.EnumerateArray()) required.Add(r.GetString()!);
    if (d.Value.TryGetProperty("properties", out var props))
    {
        foreach (var p in props.EnumerateObject())
        {
            var (type, nullable) = TypeOf(p.Value);
            // Parameters: anything not required is optional and omitted when unset.
            var optional = !required.Contains(p.Name) || nullable;
            var t = optional && !type.EndsWith("?") ? type + "?" : type;
            Doc(sb, p.Value, "    ");
            sb.AppendLine($"    [JsonPropertyName(\"{p.Name}\")]");
            if (optional && (isParams || isBase))
                sb.AppendLine("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
            var init = !optional && type.StartsWith("List<") ? " = new();" : !optional && type == "string" ? " = \"\";" : "";
            if (!optional && !type.StartsWith("List<") && type != "string" && IsClass(type))
                init = " = new();";
            var member = Pascal(p.Name);
            if (member == name) member = type.StartsWith("List<") ? "Items" : "Value";
            sb.AppendLine($"    public {t} {member} {{ get; set; }}{init}");
        }
    }
    if (!isParams && !isBase)
    {
        sb.AppendLine("    /// <summary>Fields this version of the schema does not name.</summary>");
        sb.AppendLine("    [JsonExtensionData]");
        sb.AppendLine("    public Dictionary<string, JsonElement>? Extra { get; set; }");
    }
    sb.AppendLine("}");
    sb.AppendLine();
}

sb.AppendLine("/// <summary>A method of the API: its access, CLI command and cmdlets.</summary>");
sb.AppendLine("public sealed record PaguroMethodInfo(string Name, string Access, string Cli, IReadOnlyList<string> CliExample, IReadOnlyList<string> Cmdlets, System.Type Params, System.Type Result, bool Progress, string? Stub, IReadOnlyList<string> Gated, bool DryRunRead);");
